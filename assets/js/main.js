(function () {
  var root = document.documentElement;
  var languageButtons = Array.prototype.slice.call(document.querySelectorAll('[data-lang]'));
  var themeToggle = document.querySelector('[data-theme-toggle]');
  var themeLabel = document.querySelector('[data-theme-label]');

  function getStoredLanguage() {
    var stored = localStorage.getItem('resumeLanguage');
    return resumeTranslations[stored] ? stored : 'zh';
  }

  function getStoredTheme() {
    var stored = localStorage.getItem('resumeTheme');
    if (stored === 'light' || stored === 'dark') {
      return stored;
    }
    return window.matchMedia && window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
  }

  function translatePage(language) {
    var dictionary = resumeTranslations[language] || resumeTranslations.zh;
    Array.prototype.forEach.call(document.querySelectorAll('[data-i18n]'), function (element) {
      var key = element.getAttribute('data-i18n');
      if (dictionary[key]) {
        element.textContent = dictionary[key];
      }
    });

    root.lang = language === 'en' ? 'en' : 'zh-CN';
    languageButtons.forEach(function (button) {
      var isActive = button.getAttribute('data-lang') === language;
      button.classList.toggle('is-active', isActive);
      button.setAttribute('aria-pressed', String(isActive));
    });
  }

  function applyTheme(theme, language) {
    var nextTheme = theme === 'dark' ? 'dark' : 'light';
    var dictionary = resumeTranslations[language] || resumeTranslations.zh;

    root.setAttribute('data-theme', nextTheme);
    if (themeToggle) {
      var isDark = nextTheme === 'dark';
      themeToggle.setAttribute('aria-pressed', String(isDark));
      themeToggle.querySelector('.fa').className = isDark ? 'fa fa-sun-o' : 'fa fa-moon-o';
      if (themeLabel) {
        themeLabel.textContent = dictionary[isDark ? 'controls.light' : 'controls.dark'];
      }
    }
  }

  function setLanguage(language) {
    var nextLanguage = resumeTranslations[language] ? language : 'zh';
    localStorage.setItem('resumeLanguage', nextLanguage);
    translatePage(nextLanguage);
    applyTheme(root.getAttribute('data-theme'), nextLanguage);
  }

  function setTheme(theme) {
    var nextTheme = theme === 'dark' ? 'dark' : 'light';
    localStorage.setItem('resumeTheme', nextTheme);
    applyTheme(nextTheme, getStoredLanguage());
  }

  languageButtons.forEach(function (button) {
    button.addEventListener('click', function () {
      setLanguage(button.getAttribute('data-lang'));
    });
  });

  if (themeToggle) {
    themeToggle.addEventListener('click', function () {
      setTheme(root.getAttribute('data-theme') === 'dark' ? 'light' : 'dark');
    });
  }

  translatePage(getStoredLanguage());
  applyTheme(getStoredTheme(), getStoredLanguage());
}());
